#!/usr/bin/env python3
"""Bounded small-transfer throughput measurements, separate from reachability."""
import argparse
import ctypes
import datetime as dt
import gzip
import json
import os
from pathlib import Path
import statistics
import subprocess
import sys
import time

from network_monitor import DEFAULT_LOG_DIR, TZ, append_log, atomic_json, lock, route_info

SPEED_INTERVAL = 300
DOWNLOAD_BYTES = 2_000_000
UPLOAD_BYTES = 1_000_000
DAILY_BUDGET = 1_000_000_000
METHOD = "small_single_https_transfer_v2_standard"


def execution_context():
    background = None
    if sys.platform == "darwin":
        libc = ctypes.CDLL(None, use_errno=True)
        libc.getpriority.argtypes = [ctypes.c_int, ctypes.c_uint]
        libc.getpriority.restype = ctypes.c_int
        ctypes.set_errno(0)
        value = libc.getpriority(4, 0)  # PRIO_DARWIN_PROCESS, verified in sys/resource.h.
        if ctypes.get_errno() == 0:
            background = bool(value)
    return {"darwin_background": background,
            "nice": os.getpriority(os.PRIO_PROCESS, 0),
            "runner": "launchd" if os.environ.get("XPC_SERVICE_NAME") == "com.ankimo.network-speed" else "manual"}


def transfer(direction, size):
    args = ["/usr/bin/curl", "--ipv4", "--silent", "--show-error", "--output", "/dev/null",
            "--connect-timeout", "2", "--max-time", "8", "--write-out", "%{json}"]
    payload = None
    if direction == "download":
        args += ["--header", "Cache-Control: no-cache",
                 "https://speed.cloudflare.com/__down?bytes=" + str(size)]
    elif direction == "upload":
        payload = os.urandom(size)  # Generated bytes only; never upload user files.
        args += ["--header", "Content-Type: application/octet-stream", "--header", "Expect:",
                 "--data-binary", "@-", "https://speed.cloudflare.com/__up"]
    else:
        raise ValueError("Unknown direction")
    try:
        result = subprocess.run(args, input=payload, capture_output=True, timeout=10)
        data = json.loads(result.stdout)
        size_field = "size_download" if direction == "download" else "size_upload"
        amount = int(data.get(size_field, 0))
        seconds = float(data.get("time_total", 0))
        status = int(data.get("http_code", 0))
        ok = result.returncode == 0 and 200 <= status < 300 and amount == size and seconds > 0
        return {"ok": ok, "code": result.returncode, "status": status,
                "expected_bytes": size, "transferred_bytes": amount,
                "seconds": seconds,
                "mbps": round(amount * 8 / seconds / 1_000_000, 2) if ok else None,
                **({"error": "incomplete_or_failed_transfer"} if not ok else {})}
    except (OSError, subprocess.TimeoutExpired, ValueError) as exc:
        return {"ok": False, "expected_bytes": size, "mbps": None, "error": type(exc).__name__}


def recent_measurements(log_dir, cutoff):
    rows = []
    cutoff_day = dt.datetime.fromtimestamp(cutoff, TZ).date()
    for path in sorted(log_dir.glob("speed-*.jsonl.gz")):
        if dt.date.fromisoformat(path.name[6:16]) < cutoff_day:
            continue
        with gzip.open(path, "rt") as handle:
            rows.extend(row for row in map(json.loads, handle) if row["epoch"] >= cutoff)
    return rows


def compare_reference(row, history):
    if not all(row.get(name, {}).get("ok") for name in ["download", "upload"]):
        return "transfer_failed", {}
    reference = {}
    for direction in ["download", "upload"]:
        candidates = [old[direction]["mbps"] for old in history
                      if old.get("route") == row.get("route")
                      and old.get("method") == row.get("method")
                      and old.get(direction, {}).get("ok")
                      and old[direction].get("expected_bytes") == row[direction]["expected_bytes"]]
        if len(candidates) >= 3:
            median = statistics.median(candidates)
            reference[direction] = {"samples": len(candidates), "median_mbps": round(median, 2),
                                    "ratio": round(row[direction]["mbps"] / median, 3) if median else None}
    below = any(r.get("ratio") is not None and r["ratio"] < 0.3 for r in reference.values())
    return "below_recent_baseline" if below else "measured", reference


def run_once(log_dir, force=False):
    with lock(log_dir, name=".speed.lock") as acquired:
        if not acquired:
            return {"skipped": "another_speed_test_running"}
        now = time.time()
        at = dt.datetime.fromtimestamp(now, TZ)
        latest_path = log_dir / "speed-latest.json"
        previous = json.loads(latest_path.read_text()) if latest_path.exists() else {}
        if not force and previous.get("method") == METHOD and 0 <= now - previous.get("epoch", 0) < SPEED_INTERVAL - 1:
            return {"skipped": "minimum_interval"}
        row = {"at": at.isoformat(timespec="seconds"), "epoch": round(now, 3),
               "method": METHOD, "execution": execution_context(),
               "target": "speed.cloudflare.com", "route": route_info()}
        budget_path = log_dir / "speed-budget.json"
        budget = json.loads(budget_path.read_text()) if budget_path.exists() else {}
        day = at.date().isoformat()
        used = budget.get("reserved_bytes", 0) if budget.get("day") == day else 0
        cost = DOWNLOAD_BYTES + UPLOAD_BYTES
        if not row["route"].get("ok"):
            row["condition"] = "skipped_no_default_route"
        elif row["execution"]["darwin_background"] is True:
            row["condition"] = "invalid_background_execution"
        elif used + cost > DAILY_BUDGET:
            row["condition"] = "skipped_daily_budget"
        else:
            # Reserve the maximum payload first, even if a timeout/crash sends less.
            atomic_json(budget_path, {"day": day, "reserved_bytes": used + cost,
                                      "limit_bytes": DAILY_BUDGET})
            active_path = log_dir / "speed-active.json"
            active = {"started_epoch": now, "ended_epoch": None}
            atomic_json(active_path, active)
            try:
                row["download"] = transfer("download", DOWNLOAD_BYTES)
                row["upload"] = transfer("upload", UPLOAD_BYTES)
            finally:
                active["ended_epoch"] = time.time()
                atomic_json(active_path, active)
            history = recent_measurements(log_dir, now - 24 * 3600)
            row["condition"], row["reference"] = compare_reference(row, history)
            row["ended_at"] = dt.datetime.now(TZ).isoformat(timespec="seconds")
            row["reserved_bytes_today"] = used + cost
        append_log(log_dir / ("speed-" + day + ".jsonl.gz"), row)
        atomic_json(latest_path, row)
        return row


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--once", action="store_true")
    parser.add_argument("--now", action="store_true", help="Ignore cadence, but honor daily data budget")
    parser.add_argument("--log-dir", type=Path, default=DEFAULT_LOG_DIR)
    args = parser.parse_args()
    os.umask(0o077)
    try:
        result = run_once(args.log_dir, args.now)
    except Exception as exc:
        args.log_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
        atomic_json(args.log_dir / "speed-error.json", {"at": dt.datetime.now(TZ).isoformat(),
                    "error": type(exc).__name__, "message": str(exc)[:500]})
        raise
    if not args.once:
        print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
